use allcrypt::block_ciphers::{blowfish::Blowfish, BlockCipher};

#[test]
fn test_blowfish_block() {
    let key: Vec<u8> = vec![0; 8];
    let plain: Vec<u8> = vec![0; 8];
    //FEDCBA9876543210        0123456789ABCDEF        0ACEAB0FC6A0A28D
    //let key = vec![0xFE, 0xDC, 0xBA, 0x98, 0x76, 0x54, 0x32, 0x10];
    //let plain = vec![0x01, 0x23, 0x45, 0x67, 0x89, 0xAB, 0xCD, 0xEF];
    let cipher: Vec<u8> = vec![0x4E, 0xF9, 0x97, 0x45, 0x61, 0x98, 0xDD, 0x78];

    let mut result = vec![];

    let mut crypto = Blowfish::new(key).unwrap();
    crypto.block_encrypt(&plain, &mut result);
    assert_eq!(result,cipher);

    result.clear();
    crypto.block_decrypt(&cipher, &mut result);
    assert_eq!(result, plain);
}

#[test]
fn test_blowfish_cbc() {
    let key = vec![0x01, 0x23, 0x45, 0x67, 0x89, 0xAB, 0xCD, 0xEF,
                             0xF0, 0xE1, 0xD2, 0xC3, 0xB4, 0xA5, 0x96, 0x87];
    let iv = vec![0xFE, 0xDC, 0xBA, 0x98, 0x76, 0x54, 0x32, 0x10];
    let data = "7654321 Now is the time for \x00\x00\x00\x00".as_bytes();
    let cbc_cipher = vec![0x6B, 0x77, 0xB4, 0xD6, 0x30, 0x06, 0xDE, 0xE6,
                                    0x05, 0xB1, 0x56, 0xE2, 0x74, 0x03, 0x97, 0x93,
                                    0x58, 0xDE, 0xB9, 0xE7, 0x15, 0x46, 0x16, 0xD9,
                                    0x59, 0xF1, 0x65, 0x2B, 0xD5, 0xFF, 0x92, 0xCC];
    let mut result = vec![];

    let mut crypto = Blowfish::new(key).unwrap();
    crypto.cbc_encrypt(data, &mut result, iv.to_vec()).unwrap();
    assert_eq!(result, cbc_cipher);

    result.clear();
    crypto.cbc_decrypt(&cbc_cipher, &mut result, iv).unwrap();
    assert_eq!(result, data);

}

