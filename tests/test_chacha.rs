/// Regression: `crypt()` advanced `key_pos` by the number of bytes that had
/// been *left* in the buffered block instead of by the number consumed, so
/// the third and later calls on one object read the keystream at the wrong
/// offset. Two calls were not enough to expose it, which is why the existing
/// split test passed. Reference: RFC 8439 keystream for an all-zero key and
/// nonce, cross-checked against OpenSSL.
#[test]
fn test_chacha20_many_small_calls() {
    let key = vec![0u8; 32];
    let nonce = vec![0u8; 12];

    // One byte at a time must equal the one-shot result.
    let mut c = Chacha::new(key.clone(), nonce.clone(), 20).unwrap();
    let mut streamed = vec![];
    for _ in 0..200 {
        c.crypt(&[0u8], &mut streamed);
    }

    let mut c = Chacha::new(key.clone(), nonce.clone(), 20).unwrap();
    let mut one_shot = vec![];
    c.crypt(&[0u8; 200], &mut one_shot);

    assert_eq!(streamed, one_shot);
    assert_eq!(allcrypt::to_hex(&one_shot[..3]).to_lowercase(), "76b8e0");

    // Irregular splits, including ones that straddle the 64 byte block edge.
    for first in [1usize, 3, 7, 31, 33, 63, 64, 65, 100] {
        let plain: Vec<u8> = (0..500).map(|i| (i & 0xff) as u8).collect();
        let mut c = Chacha::new(key.clone(), nonce.clone(), 20).unwrap();
        let mut streamed = vec![];
        let (mut i, mut step) = (0usize, first);
        while i < plain.len() {
            let e = std::cmp::min(plain.len(), i + step);
            c.crypt(&plain[i..e], &mut streamed);
            i = e;
            step = step * 2 + 1;
        }
        let mut c = Chacha::new(key.clone(), nonce.clone(), 20).unwrap();
        let mut one_shot = vec![];
        c.crypt(&plain, &mut one_shot);
        assert_eq!(streamed, one_shot, "split starting at {}", first);
    }
}

/// The round count is restricted to the three defined variants; 0 rounds used
/// to be accepted and produced a trivially invertible keystream.
#[test]
fn test_chacha_rejects_bad_rounds() {
    let key = vec![0u8; 32];
    let nonce = vec![0u8; 12];
    assert!(Chacha::new(key.clone(), nonce.clone(), 0).is_err());
    assert!(Chacha::new(key.clone(), nonce.clone(), 7).is_err());
    assert!(Chacha::new(key.clone(), nonce.clone(), 21).is_err());
    for r in [8usize, 12, 20] {
        assert!(Chacha::new(key.clone(), nonce.clone(), r).is_ok());
    }
}
