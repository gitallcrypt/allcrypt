//! Trivium, Grain v1 and Grain-128 through the stream cipher facade,
//! against two sources. Offline.
//!
//! The eSTREAM project's own test vectors, `vectors/estream/*.test-vectors`,
//! read here as published: each vector's stretches of keystream and its
//! `xor-digest`, the XOR of every 64 byte block of the whole keystream,
//! so every byte of it is checked.
//!
//! `vectors/trivium_grain.vec`, written by
//! `scripts/make_trivium_grain_vectors.py`: random keys and IVs at lengths
//! either side of the steps the ciphers are computed in, every row given
//! by every witness that can answer it, each taken in one call and in
//! pieces of 1, 2, 3 .. bytes.

use std::collections::{BTreeMap, HashMap};

use allcrypt::api::AnyStreamCipher;

fn unhex(s: &str) -> Vec<u8> {
    (0..s.len()).step_by(2).map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap()).collect()
}

/// One vector of an eSTREAM file.
#[derive(Default)]
struct Vector {
    label: String,
    key: Vec<u8>,
    iv: Vec<u8>,
    length: usize,
    stretches: Vec<(usize, Vec<u8>)>,
    digest: Vec<u8>,
}

/// The vectors of an eSTREAM test-vector file. A set whose header says
/// "(stream is generated by encrypting N zero bytes)" covers N bytes; a
/// set without one - 4 and 6 - covers up to the end of its last stretch.
fn read_estream(text: &str) -> Vec<Vector> {
    let mut vectors: Vec<Vector> = Vec::new();
    let mut length = None;
    let mut field = "";
    for line in text.lines() {
        let trimmed = line.trim();
        if line.starts_with("Test vectors -- set") {
            length = None;
            continue;
        }
        if let Some(rest) = trimmed.strip_prefix("(stream is generated by encrypting ") {
            length = Some(rest.split(' ').next().unwrap().parse::<usize>().unwrap());
            continue;
        }
        if line.starts_with("Set ") && line.contains("vector#") {
            vectors.push(Vector { label: line.trim_end_matches(':').to_string(),
                                  length: length.unwrap_or(0), ..Vector::default() });
            field = "";
            continue;
        }
        let Some(v) = vectors.last_mut() else { continue };
        if let Some((name, value)) = trimmed.split_once(" = ") {
            let value = unhex(value);
            field = match name {
                "key" => { v.key = value; "key" }
                "IV" => { v.iv = value; "iv" }
                "xor-digest" => { v.digest = value; "digest" }
                stream => {
                    let range = stream.strip_prefix("stream[").unwrap().trim_end_matches(']');
                    let start = range.split("..").next().unwrap().parse().unwrap();
                    v.stretches.push((start, value));
                    "stretch"
                }
            };
        } else if !trimmed.is_empty() && trimmed.bytes().all(|b| b.is_ascii_hexdigit()) {
            let value = unhex(trimmed);
            match field {
                "key" => v.key.extend(value),
                "iv" => v.iv.extend(value),
                "digest" => v.digest.extend(value),
                "stretch" => v.stretches.last_mut().unwrap().1.extend(value),
                _ => panic!("hex outside a field: {line}"),
            }
        } else if trimmed.is_empty() {
            field = "";
        }
    }
    for v in &mut vectors {
        if v.length == 0 {
            v.length = v.stretches.iter().map(|(start, _)| start + 64).max().unwrap();
        }
        assert_eq!(v.digest.len(), 64, "{}", v.label);
        assert!(v.stretches.iter().all(|(_, s)| s.len() == 64), "{}", v.label);
    }
    vectors
}

fn xor_digest(keystream: &[u8]) -> Vec<u8> {
    let mut digest = vec![0u8; 64];
    for block in keystream.chunks(64) {
        for (d, b) in digest.iter_mut().zip(block) {
            *d ^= b;
        }
    }
    digest
}

#[test]
fn test_the_estream_vectors() {
    for (file, cipher, count) in [
        (include_str!("../vectors/estream/trivium-unverified.test-vectors"), "trivium", 246),
        (include_str!("../vectors/estream/grain-v1-verified.test-vectors"), "grainv1", 83),
        (include_str!("../vectors/estream/grain-128-unverified.test-vectors"), "grain128", 92),
    ] {
        let vectors = read_estream(file);
        // A parser that found nothing would pass every assertion below.
        assert_eq!(vectors.len(), count, "{cipher}");
        let mut iv_lengths = BTreeMap::new();
        for v in &vectors {
            let mut c = AnyStreamCipher::new(cipher, &v.key, &v.iv).unwrap();
            let keystream = c.encrypt(&vec![0u8; v.length]).unwrap();
            for (start, stretch) in &v.stretches {
                assert_eq!(&keystream[*start..start + 64], &stretch[..], "{cipher} {} at {start}",
                           v.label);
            }
            assert_eq!(xor_digest(&keystream), v.digest, "{cipher} {} digest", v.label);
            *iv_lengths.entry(v.iv.len()).or_insert(0) += 1;
        }
        if cipher == "trivium" {
            // The file's three IV lengths: 32, 64 and 80 bits.
            assert_eq!(iv_lengths.keys().copied().collect::<Vec<_>>(), [4, 8, 10]);
        }
    }
}

#[test]
fn test_the_witness_rows() {
    let mut seen: BTreeMap<String, usize> = BTreeMap::new();
    for line in include_str!("../vectors/trivium_grain.vec").lines() {
        if !line.starts_with("stream ") {
            continue;
        }
        let f: HashMap<&str, &str> = line.split(' ').skip(1)
            .map(|w| w.split_once('=').unwrap()).collect();
        let (cipher, key, iv, want) = (f["cipher"], unhex(f["key"]), unhex(f["iv"]),
                                       unhex(f["keystream"]));
        assert!(f["witnesses"].split(',').count() >= 2, "{line}");
        let zeros = vec![0u8; want.len()];
        let mut c = AnyStreamCipher::new(cipher, &key, &iv).unwrap();
        assert_eq!(c.encrypt(&zeros).unwrap(), want, "{}", &line[..line.len().min(120)]);
        let mut c = AnyStreamCipher::new(cipher, &key, &iv).unwrap();
        let (mut got, mut at, mut piece) = (Vec::new(), 0, 1);
        while at < zeros.len() {
            let end = (at + piece).min(zeros.len());
            got.extend(c.update(&zeros[at..end]).unwrap());
            at = end;
            piece += 1;
        }
        assert_eq!(got, want, "{} in pieces", &line[..line.len().min(120)]);
        *seen.entry(format!("{cipher}/{}", iv.len())).or_default() += 1;
    }
    for (shape, at_least) in [("trivium/10", 20), ("trivium/8", 5), ("trivium/6", 5),
                              ("trivium/4", 5), ("grainv1/8", 20), ("grain128/12", 20)] {
        assert!(seen.get(shape).copied().unwrap_or(0) >= at_least, "{shape}: {seen:?}");
    }
}

/// The names the facade answers to, and that none of them seeks.
#[test]
fn test_names_and_no_seeking() {
    for (name, key, iv) in [("trivium", 10, 10), ("grainv1", 10, 8), ("grain-v1", 10, 8),
                            ("grain128", 16, 12), ("grain-128", 16, 12)] {
        let mut c = AnyStreamCipher::new(name, &vec![7; key], &vec![9; iv]).unwrap();
        assert!(c.seek(0).is_err(), "{name}");
    }
}
