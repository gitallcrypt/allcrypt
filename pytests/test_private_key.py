@pytest.mark.parametrize("name", [
    "rsa_pbes2_aes128.pem", "rsa_pbes2_aes256.pem", "rsa_pbes2_3des.pem",
    "rsa_pbes2_aes256_prf_sha256.pem", "rsa_pbes2_aes256_prf_sha512.pem",
    "rsa_pkcs12_sha1_3des.pem", "rsa_pkcs12_sha1_rc2_40.pem",
    "rsa_pkcs12_sha1_rc4_128.pem", "rsa_pbes1_md5_des.pem",
])
def test_the_decrypted_key_agrees_with_python_cryptography(name):
    """Differential, for the schemes cryptography will still read.

    Not all of them: `pbeWithSHA1AndDES-CBC` and `pbeWithMD5AndRC2-CBC`
    are refused there with "Unknown key encryption algorithm", and
    `-v2 des-cbc` and `-v2 rc2-cbc` need OpenSSL's legacy provider. Those
    rows are checked against the pinned plaintext in the Rust suite
    instead, which is the weaker form of evidence and the only one
    available - and the reason the fixtures are pinned at all.
    """
    from cryptography.hazmat.primitives.serialization import load_pem_private_key
    theirs = load_pem_private_key(_fixture(name), b"secret")
    ours = allcrypt.private_key(_fixture(name), b"secret")
    # `numbers` gives big-endian bytes; cryptography gives ints.
    as_int = lambda b: int.from_bytes(b, "big")
    assert as_int(ours.numbers["n"]) == theirs.private_numbers().public_numbers.n, name
    assert as_int(ours.numbers["p"]) == theirs.private_numbers().p, name
    assert as_int(ours.numbers["q"]) == theirs.private_numbers().q, name


def test_the_schemes_this_machine_can_no_longer_produce_are_still_read():
    """The point of the whole exercise, stated as a test.

    These four fixtures cannot be regenerated on this machine without
    `-provider legacy`, and two of them cannot be read by
    python-cryptography at all. They are checked in, and they open.
    """
    want = allcrypt.private_key(_fixture("rsa_plain.pem")).numbers["n"]
    for name in ["rsa_pbes1_sha1_des.pem", "rsa_pbes1_md5_rc2.pem",
                 "rsa_pbes2_des.pem", "rsa_pbes2_rc2.pem"]:
        assert allcrypt.private_key(_fixture(name), b"secret").numbers["n"] == want, name


# ------------------------------------------------------- encrypting keys ---

def _pem_der(pem):
    import base64
    lines = pem.decode().strip().splitlines()
    return base64.b64decode("".join(lines[1:-1]))


@pytest.mark.parametrize("name", [
    "rsa_pbes2_aes128.pem", "rsa_pbes2_aes256.pem", "rsa_pbes2_3des.pem",
    "rsa_pbes2_des.pem", "rsa_pbes2_rc2.pem", "rsa_pbes2_aes256_prf_sha1.pem",
    "rsa_pbes2_aes256_prf_sha512.pem", "rsa_pbes1_md5_des.pem", "rsa_pbes1_md5_rc2.pem",
    "rsa_pkcs12_sha1_3des.pem", "rsa_pkcs12_sha1_rc2_40.pem", "rsa_pkcs12_sha1_rc4_128.pem",
])
def test_encrypting_with_a_files_parameters_reproduces_it(name):
    """Given an OpenSSL file's salt, count and IV, the plain key encrypts
    to that file again, byte for byte."""
    p = allcrypt.private_key_encryption(_fixture(name))
    again = allcrypt.encrypt_private_key(
        _fixture("rsa_plain.pem"), b"secret", p["scheme"], prf=p["prf"],
        iterations=p["iterations"], salt=p["salt"], iv=p["iv"] or None)
    assert again == _pem_der(_fixture(name)), (name, p["scheme"])


@pytest.mark.parametrize("scheme", ["aes-128-cbc", "aes-256-cbc", "des-ede3-cbc",
                                    "pbe-sha1-3des", "pbe-sha1-rc2-40", "pbe-sha1-rc4-128",
                                    "pbe-md5-des"])
def test_python_cryptography_reads_what_is_written(scheme):
    from cryptography.hazmat.primitives.serialization import load_der_private_key
    plain = _fixture("ec_plain.pem")
    sealed = allcrypt.encrypt_private_key(plain, b"pw", scheme, iterations=10)
    theirs = load_der_private_key(sealed, b"pw")
