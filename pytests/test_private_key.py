def test_a_certificate_and_key_in_one_file_finds_the_key():
    """The normal deployment shape - what `load_cert_chain` is handed."""
    import datetime
    from cryptography import x509
    from cryptography.x509.oid import NameOID

    key = ec.generate_private_key(ec.SECP256R1())
    name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, "localhost")])
    now = datetime.datetime.now(datetime.timezone.utc)
    certificate = (x509.CertificateBuilder()
                   .subject_name(name).issuer_name(name)
                   .public_key(key.public_key()).serial_number(1)
                   .not_valid_before(now - datetime.timedelta(days=1))
                   .not_valid_after(now + datetime.timedelta(days=1))
                   .sign(key, hashes.SHA256()))
    combined = (certificate.public_bytes(PEM)
                + key.private_bytes(PEM, PKCS8, NOTHING))
    ours = allcrypt.private_key(combined)
    assert ours.private_bytes() == \
        key.private_numbers().private_value.to_bytes(32, "big")


def test_a_curve_we_cannot_compute_on_is_refused_by_name():
    """A private key on an unknown curve is nothing at all - unlike a
    *public* key in a certificate, which is still a link in a chain and
    is kept as `UnsupportedCurve`."""
    key = ec.generate_private_key(ec.BrainpoolP256R1())   # not implemented here
    with pytest.raises(ValueError) as failure:
        allcrypt.private_key(key.private_bytes(PEM, PKCS8, NOTHING))
    assert "1.3.36.3.3.2.8.1.1.7" in str(failure.value)


def test_garbage_is_an_error_and_never_a_panic():
    key = ec.generate_private_key(ec.SECP256R1())
    der = key.private_bytes(DER, PKCS8, NOTHING)
    for cut in range(1, len(der)):
        with pytest.raises(ValueError):
            allcrypt.private_key(der[:cut])
    for flip in range(0, len(der), 7):
        broken = bytearray(der)
        broken[flip] ^= 0xff
        try:
            allcrypt.private_key(bytes(broken))
        except ValueError:
            pass


# --------------------------------------------------------- encrypted keys ---
#
# The Rust suite (`tests/test_encrypted_keys.rs`) checks the fixtures in
# `tests/keys/`, which are pinned because the OpenSSL that produced them
# is already losing the ability to. These check the *Python* surface and
# the one thing the Rust side cannot: agreement with python-cryptography
