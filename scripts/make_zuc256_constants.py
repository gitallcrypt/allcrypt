#!/usr/bin/env python3
"""Write src/stream_ciphers/zuc256_constants.rs: ZUC-256's loading constants.

    sh scripts/witness/snow3g_zuc/build.sh /opt/gppwitness
    python3 scripts/make_zuc256_constants.py [/opt/gppwitness] [--check]

**A development tool, not a test.** ZUC-256 ("The ZUC-256 Stream
Cipher", the ZUC design team, 2018) loads its LFSR with sixteen seven bit
constants `d_0 .. d_15`, one set for the keystream and one for each MAC
tag size. The paper is not vendored here, so the four sets are read out
of two implementations that were written independently - GmSSL's
`ZUC256_D` table (`src/zuc.c`) and intel-ipsec-mb's `EK256_d64` and
`EK256_EIA3_4/8/16` (`lib/avx512_t1/zuc_x16_avx512.asm`, each value
shifted up sixteen bits) - from the trees `scripts/witness/snow3g_zuc/
build.sh` fetches, and written only when the two agree. Bouncy Castle's
`Zuc256CoreEngine` and the zuc crate carry the same four sets. With
`--check` the file is compared and not written.

Whether the constants are right is then a matter for the vectors: Intel's
ZUC-256 keystream and MAC tests (vectors/zuc256/) and the witnesses'
agreement in vectors/snow3g_zuc.vec.
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "src", "stream_ciphers", "zuc256_constants.rs")
NAMES = ["KEYSTREAM", "MAC32", "MAC64", "MAC128"]


def from_gmssl(out):
    with open(os.path.join(out, "src", "guanzhi-GmSSL", "src", "zuc.c")) as handle:
        text = handle.read()
    body = re.search(r"ZUC256_D\[\]\[16\]\s*=\s*\{(.*?)\};", text, re.S).group(1)
    rows = re.findall(r"\{([^}]*)\}", body)
    return [[int(v, 16) for v in re.findall(r"0x[0-9A-Fa-f]+", row)] for row in rows]


def from_ipsecmb(out):
    path = os.path.join(out, "src", "ipsecmb-tagged", "lib", "avx512_t1", "zuc_x16_avx512.asm")
    with open(path) as handle:
        text = handle.read()
    sets = []
    for label in ("EK256_d64", "EK256_EIA3_4", "EK256_EIA3_8", "EK256_EIA3_16"):
        body = re.search(rf"^{label}:\n((?:dd[^\n]*\n)+)", text, re.M).group(1)
        values = [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]{8})", body)]
        assert all(v & 0xff00ffff == 0 for v in values), label
        sets.append([v >> 16 for v in values])
    return sets


def render(sets):
    lines = [
        "// GENERATED by scripts/make_zuc256_constants.py - do not edit.",
        "//",
        "// ZUC-256's LFSR loading constants d_0 .. d_15, seven bits each: one set",
        "// for the keystream and one for each MAC tag size. Read from GmSSL's",
        "// ZUC256_D and intel-ipsec-mb's EK256_d64 and EK256_EIA3_4/8/16, which",
        "// agree; the script says from which trees.",
        "",
    ]
    for name, values in zip(NAMES, sets):
        what = "the keystream" if name == "KEYSTREAM" else f"the {name[3:]} bit MAC"
        lines.append(f"/// d_0 .. d_15 for {what}.")
        lines.append(f"pub(crate) const {name}: [u8; 16] = [")
        lines.append("    " + ", ".join(f"0x{v:02x}" for v in values[:8]) + ",")
        lines.append("    " + ", ".join(f"0x{v:02x}" for v in values[8:]) + ",")
        lines.append("];")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    out = args[0] if args else "/opt/gppwitness"
    gmssl, ipsecmb = from_gmssl(out), from_ipsecmb(out)
    if len(gmssl) != 4 or any(len(s) != 16 for s in gmssl + ipsecmb):
        sys.exit("a source no longer has four sets of sixteen constants")
    if gmssl != ipsecmb:
        sys.exit(f"GmSSL and intel-ipsec-mb disagree:\n{gmssl}\n{ipsecmb}")
    if any(v >= 0x80 for s in gmssl for v in s):
        sys.exit("a constant has more than seven bits")
    text = render(gmssl)
    if "--check" in sys.argv:
        with open(OUTPUT) as handle:
            if handle.read() != text:
                sys.exit(f"{OUTPUT} differs from what the sources give")
        print(f"{OUTPUT} is current")
        return
    with open(OUTPUT, "w") as handle:
        handle.write(text)
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
